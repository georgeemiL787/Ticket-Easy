def make_customers(n, taken_emails):
    cities = [c for c in K.CITIES]
    weights = [c[1] for c in cities]
    langs, lang_w = ("en", "ar", "mixed", "arabizi"), (25, 35, 20, 20)
    rows, extra, used_email = [], {}, set(taken_emails)
    for i in range(n):
        cid = f"C-{20001 + i}"
        female = rnd.random() < 0.5
        first = rnd.choice(K.FEMALE if female else K.MALE)
        last = rnd.choice(K.LAST)
        city = rnd.choices(cities, weights)[0]
        base = f"{first[0]}.{last[0]}".lower()
        email = f"{base}@example.com"
        k = 2
        while email in used_email:
            email, k = f"{base}{k}@example.com", k + 1
        used_email.add(email)
        verified = rnd.random() < 0.9
        member = AS_OF - timedelta(days=int(rnd.triangular(20, 2400, 300)))
        rows.append({
            "customer_id": cid, "tenant_id": TENANT, "name_en": f"{first[0]} {last[0]}",
            "name_ar": f"{first[1]} {last[1]}", "phone": f"0100 {1 + i // 10000:03d} {i % 10000:04d}",
            "email": email, "city": city[0], "preferred_language": rnd.choices(langs, lang_w)[0],
            "verified": verified,
            "verified_via": (rnd.choices(["otp_sms", "otp_email"], (85, 15))[0] if verified else None),
            "noon_wallet_egp": 0, "member_since": iso(member),
        })
        extra[cid] = {"female": female, "city": city}
    return rows, extra


# ------------------------------------------------------------------ orders

def day_weights():
    """Placement weight per day over the last year: White Friday, Ramadan/Eid and back-to-school peaks."""
    days, weights = [], []
    for k in range(0, 366):
        d = AS_OF - timedelta(days=k)
        w = 1.0
        if date(2025, 11, 20) <= d <= date(2025, 11, 30):
            w = 3.2
        elif date(2026, 2, 18) <= d <= date(2026, 3, 19):
            w = 1.6
        elif date(2026, 9, 1) <= d <= date(2026, 9, 25):
            w = 1.5
        w *= 1 + 0.35 * (1 - k / 365)  # the shop grew over the year
        days.append(d)
        weights.append(w)
    return days, weights


PRODUCT_KEYS = list(K.PRODUCTS)
PRODUCT_W = [K.PRODUCTS[k][0] for k in PRODUCT_KEYS]
MINUTES_KEYS = [k for k in PRODUCT_KEYS if K.PRODUCTS[k][2] and K.PRODUCTS[k][1][1] <= 9500]
MINUTES_W = [K.PRODUCTS[k][0] * (3 if k[0] == "grocery" else 1) for k in MINUTES_KEYS]


def make_item(oid, n, key, section):
    cat, sub = key
    _, (lo, hi), _, names = K.PRODUCTS[key]
    name = rnd.choice(names)
    qty = rnd.choices([1, 2, 3], (85, 11, 4))[0] if hi < 800 else 1
    if section == "minutes":
        tag = cat in {"electronics", "beauty_health", "home_kitchen", "sports", "toys", "baby", "automotive",
                      "tools", "pet_supplies", "stationery"} and rnd.random() < 0.85
        warranty = cat in {"electronics", "home_kitchen", "automotive", "tools"} and sub not in {"kitchenware", "home_decor", "hand_tool", "car_accessory"} and rnd.random() < 0.35
    else:
        tag = rnd.random() < (0.25 if cat == "grocery" else 0.88)
        warranty = False
    return {"item_id": f"{oid}-I{n}", "sku": f"SKU-{zlib.crc32(name.encode()) % 100000:05d}", "name": name,
            "category": cat, "product_subcategory": sub, "qty": qty, "price_egp": price(lo, hi),
            "return_eligible_tag": tag, "warranty_tag": warranty,
            "item_condition": K.default_condition(cat, sub), "is_clearance": False}


def payment_for(section, total):
    if section == "minutes":
        return rnd.choices(["cash_on_delivery", "credit_card"], (55, 45))[0]
    # only the payment values in the shared vocabulary (data/shared/vocabulary.json)
    pm = rnd.choices(["cash_on_delivery", "credit_card", "bnpl_tabby", "credit_card_emi"], (42, 42, 9, 7))[0]
    if pm == "credit_card_emi" and total < 3000:
        pm = "credit_card"
    return pm


def make_orders(customers, extra):
    days, weights = day_weights()
    orders, seq = [], 100000
    plan = []
    for c in customers:
        n = rnd.choices([0, 1, 2, 3, 5, 8, 14, 25], (7, 18, 16, 15, 18, 14, 9, 3))[0]
        if n > 2:
            n = rnd.randint(max(1, n - 2), n + 2)
        member = date.fromisoformat(c["member_since"])
        for _ in range(n):
            d = rnd.choices(days, weights)[0]
            plan.append((max(d, member), c))
    plan.sort(key=lambda p: (p[0], p[1]["customer_id"]))
    for placed, c in plan:
        seq += 1
        oid = f"ORD-{seq}"
        city = extra[c["customer_id"]]["city"]
        section = "minutes" if city[3] and rnd.random() < 0.22 else "noon"
        if section == "minutes":
            keys = rnd.choices(MINUTES_KEYS, MINUTES_W, k=rnd.choices([1, 2, 3, 4, 5], (35, 28, 18, 12, 7))[0])
        else:
            keys = rnd.choices(PRODUCT_KEYS, PRODUCT_W, k=rnd.choices([1, 2, 3, 4], (66, 24, 7, 3))[0])
        items = [make_item(oid, n, k, section) for n, k in enumerate(dict.fromkeys(keys), start=1)]
        sub = sum(i["price_egp"] * i["qty"] for i in items)
        if section == "minutes":
            shipping = 0 if sub >= MINUTES_FREE_SHIPPING else MINUTES_SHIPPING
            eta = placed
        else:
            shipping = 0 if sub >= NOON_FREE_SHIPPING else NOON_SHIPPING
            lo, hi = city[2]
            if any(i["product_subcategory"] in {"furniture", "large_appliance"} for i in items):
                lo, hi = lo + 2, hi + 4
            eta = placed + timedelta(days=rnd.randint(lo, hi))
        pm = payment_for(section, sub + shipping)
        cod = COD_FEE if pm == "cash_on_delivery" else 0
        r = rnd.random()
        delivered, status = None, None
        if section == "minutes":
            delivered = placed
        elif r < 0.035:
            delivered = eta + timedelta(days=rnd.randint(3, 9))   # late but arrived
        else:
            delivered = eta + timedelta(days=rnd.choice([-1, 0, 0, 0, 0, 1]))
            delivered = max(delivered, placed + timedelta(days=1))
        if rnd.random() < (0.02 if section == "minutes" else 0.045):
            status, delivered = "cancelled", None
        elif delivered > AS_OF:
            stuck = section == "noon" and eta < AS_OF and rnd.random() < 0.3
            if placed >= AS_OF - timedelta(days=1) and not stuck:
                status = "processing"
            else:
                status = "shipped"
            delivered = None
        elif section == "noon" and AS_OF - timedelta(days=20) < eta < AS_OF and rnd.random() < 0.012:
            status, delivered = "shipped", None                    # delayed, past its expected date
        else:
            status = "delivered"
        orders.append({
            "order_id": oid, "tenant_id": TENANT, "customer_id": c["customer_id"], "section": section,
            "status": status, "placed_at": iso(placed), "expected_delivery_date": iso(eta),
            "delivered_at": iso(delivered), "payment_method": pm, "shipping_fee_egp": shipping,
            "cod_fee_egp": cod, "items": items, "total_egp": sub + shipping + cod,
        })
    return orders


# ------------------------------------------------------------------ returns

DESTINATION = {"credit_card": "original_card", "credit_card_emi": "original_card", "bnpl_tabby": "bnpl_provider",
               }
QC_FAIL = ["failed_item_used", "failed_seal_broken", "failed_missing_parts", "failed_tags_removed"]
# Order statuses stay inside the shared vocabulary: an order with only some items returned stays "delivered"
# (or "return_in_progress" while the return runs); the return record carries the detail.


def return_condition(cat, sub, section):
    if section == "noon" and cat in {"electronics", "automotive"} and rnd.random() < 0.18:
        return "defective"
    if section == "noon" and cat == "home_kitchen" and sub in {"small_appliance", "kitchenware"} and rnd.random() < 0.12:
        return "defective"
    return K.default_condition(cat, sub)


def make_returns(orders, decide):
    returns, seq = [], 60000
    for o in orders:
        if o["status"] != "delivered":
            continue
        section = o["section"]
        if rnd.random() >= (MINUTES_RETURN_RATE if section == "minutes" else NOON_RETURN_RATE):
            continue
        delivered = date.fromisoformat(o["delivered_at"])
        window = 14 if section == "minutes" else 15
        k = min(int(rnd.expovariate(1 / 4)), window)
        requested = delivered + timedelta(days=k)
        if requested > AS_OF:
            continue
        it = rnd.choice(o["items"])
        cond = return_condition(it["category"], it["product_subcategory"], section)
        dec, _, _ = decide(section, it["category"], it["product_subcategory"], cond, it["return_eligible_tag"],
                           it["warranty_tag"], k, True)
        if dec != "allow":
            continue
        it["item_condition"] = cond
        seq += 1
        pickup = requested + timedelta(days=rnd.randint(1, 3))
        received = pickup + timedelta(days=rnd.randint(1, 7) if section == "noon" else rnd.randint(1, 2))
        processed = add_business_days(received, rnd.randint(0, 2))
        amount = it["price_egp"] * it["qty"]
        fees = []
        if o["shipping_fee_egp"]:
            fees.append(f"shipping fee {o['shipping_fee_egp']} EGP")
        if o["cod_fee_egp"]:
            fees.append(f"COD fee {o['cod_fee_egp']} EGP")
        note = f"Item {it['item_id']} ({it['name']})" + (f"; {' and '.join(fees)} not refunded" if fees else "")
        rec = {"return_id": f"RET-{seq}", "tenant_id": TENANT, "order_id": o["order_id"],
               "customer_id": o["customer_id"], "payment_method": o["payment_method"],
               "requested_at": iso(requested)}
        multi = len(o["items"]) > 1
        if AS_OF < pickup:
            rec.update(status="pickup_scheduled")
        elif AS_OF < received:
            rec.update(status="in_transit")
        elif AS_OF < processed:
            rec.update(status="received_in_qc", received_at=iso(received))
        elif rnd.random() < 0.1 and cond != "defective":
            # failed quality control: Rejected Item, no refund, redelivery attempts
            rec.update(received_at=iso(received), qc_result=rnd.choice(QC_FAIL), refund_amount_egp=0,
                       refund_destination=None)
            attempts_allowed = 1 if section == "minutes" else 2
            first_attempt = processed + timedelta(days=rnd.randint(1, 2))
            if rnd.random() < 0.7:
                failed = rnd.randint(0, attempts_allowed - 1)
                back = first_attempt + timedelta(days=2 * failed)
                rec.update(status="returned_to_customer" if back <= AS_OF else "redelivery_scheduled",
                           delivery_attempts_failed=failed)
            else:
                hold = first_attempt + timedelta(days=2 * (attempts_allowed - 1) + 1)
                if hold > AS_OF:
                    rec.update(status="redelivery_scheduled", delivery_attempts_failed=attempts_allowed - 1)
                else:
                    held = business_days_between(hold, AS_OF)
                    limit = 3 if section == "minutes" else 3 + 7
                    rec.update(status="rejected_in_hub" if held <= limit else "disposed",
                               delivery_attempts_failed=attempts_allowed, hub_hold_started_at=iso(hold),
                               hub_hold_business_days=3)
            rec["notes"] = f"Item {it['item_id']} ({it['name']}) failed quality control"
        else:
            pm = o["payment_method"]
            dest = DESTINATION.get(pm)
            if pm == "cash_on_delivery":
                dest = "bank_account" if amount > 50 and rnd.random() < 0.15 else "noon_wallet"
            initiated = processed
            if dest == "noon_wallet":
                done = initiated
            elif dest == "bank_account":
                done = add_business_days(initiated, rnd.randint(3, 7))
            elif dest == "bnpl_provider":
                done = initiated + timedelta(days=rnd.randint(14, 21))
            else:
                done = add_business_days(initiated, rnd.randint(7, 14))
            rec.update(received_at=iso(received), qc_result="passed", refund_amount_egp=amount,
                       refund_destination=dest, refund_initiated_at=iso(initiated))
            if dest == "original_card" and done <= AS_OF and rnd.random() < 0.04:
                rec.update(status="refund_approved")    # bank never posted it: customer must contact the bank
            elif done <= AS_OF:
                rec.update(status="refunded", refund_completed_at=iso(done))
            else:
                rec.update(status="refund_initiated")
            rec["notes"] = note
        rec.setdefault("notes", f"Item {it['item_id']} ({it['name']})")
        returns.append(rec)
        # order status follows its return
        if rec["status"] in {"refunded", "refund_initiated", "refund_approved"}:
            o["status"] = "delivered" if multi else "returned"
        elif rec["status"] in {"pickup_scheduled", "in_transit", "received_in_qc", "redelivery_scheduled", "rejected_in_hub"}:
            o["status"] = "return_in_progress"
        o["_return"] = rec
    return returns


def settle_wallets(customers, returns):
    by_c = {c["customer_id"]: c for c in customers}
    for r in returns:
        if r.get("refund_destination") == "noon_wallet" and r["status"] == "refunded":
            if date.fromisoformat(r["refund_completed_at"]) >= AS_OF - timedelta(days=45):
                by_c[r["customer_id"]]["noon_wallet_egp"] += r["refund_amount_egp"]
    for c in customers:
        if rnd.random() < 0.12:
            c["noon_wallet_egp"] += rnd.choice([10, 20, 25, 50, 75, 100, 150, 200])


