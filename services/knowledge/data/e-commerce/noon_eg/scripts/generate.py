def load_originals(seed: Path):
    """The hand-built records (seed/, regenerated by seed/build_noon_mock_data.py) and their policy checker."""
    mock = seed
    out = {}
    for key in ("customers", "orders", "returns", "scenarios"):
        raw = json.loads((mock / f"noon_{key}.json").read_text(encoding="utf-8"))
        out[key], out["meta"] = raw[key], raw["_meta"]
    tickets = seed / "tickets.jsonl"
    out["tickets"] = [json.loads(l) for l in tickets.read_text(encoding="utf-8").splitlines() if l.strip()]
    ref = runpy.run_path(str(mock / "build_noon_mock_data.py"))  # module code only; its __main__ writer does not run
    return out, ref


