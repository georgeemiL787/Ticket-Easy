"""Tables for the chunking comparison, read only from results_<mode>.json and per_question_<mode>.jsonl.

  python docs/reports/eval_runs/chunking/build_chunking_tables.py [keyword_only|hybrid]

Writes tables_<mode>.md and pooled_<mode>.json next to this file. Pooled figures weight every question once across the
three tenants (test split). Paired tests are against the production `structure` strategy on the same questions:
exact McNemar (two-sided binomial on the discordant pairs) for hit@5, and an exact sign test for context recall.
"""

import json
import sys
from collections import defaultdict
from math import comb
from pathlib import Path

HERE = Path(__file__).resolve().parent
BASE = "structure"
SETTINGS = (("shipped", "top 5, shipped thresholds"), ("shipped_budget1500", "1500-character budget, shipped thresholds"),
            ("dev_tuned", "top 5, keyword threshold re-picked on dev per strategy"))


def binom_two_sided(k: int, n: int) -> float:
    if n == 0:
        return 1.0
    tail = sum(comb(n, i) for i in range(0, min(k, n - k) + 1)) / 2 ** n
    return min(1.0, 2 * tail)


def pct(x: float) -> str:
    return f"{100 * x:.1f}"


def pooled(rows: list[dict]) -> dict:
    ans = [r for r in rows if r["answerable"]]
    unans = [r for r in rows if not r["answerable"]]
    empties = [r for r in rows if r["returned"] == 0]
    mean = lambda xs: sum(xs) / len(xs) if xs else 0.0  # noqa: E731
    return {
        "answerable": len(ans), "unanswerable": len(unans),
        "hit_at_5": mean([r["hit"] for r in ans]),
        "context_precision": mean([r["context_precision"] for r in ans]),
        "context_recall": mean([r["context_recall"] for r in ans]),
        "char_precision": mean([r["char_precision"] for r in ans if r["returned"]]),
        "no_answer_recall": mean([r["returned"] == 0 for r in unans]),
        "no_answer_precision": (sum(not r["answerable"] for r in empties) / len(empties)) if empties else 1.0,
        "avg_returned_chars": mean([r["returned_chars"] for r in rows if r["returned"]]),
    }


def paired(rows: list[dict], base_rows: list[dict]) -> dict:
    base = {(r["tenant"], r["id"]): r for r in base_rows if r["answerable"]}
    hit_win = hit_loss = cr_win = cr_loss = 0
    for r in rows:
        b = base.get((r["tenant"], r["id"]))
        if b is None:
            continue
        hit_win += r["hit"] and not b["hit"]
        hit_loss += b["hit"] and not r["hit"]
        cr_win += r["context_recall"] > b["context_recall"] + 1e-9
        cr_loss += r["context_recall"] < b["context_recall"] - 1e-9
    return {"hit_wins": hit_win, "hit_losses": hit_loss, "hit_p": binom_two_sided(min(hit_win, hit_loss), hit_win + hit_loss),
            "cr_wins": cr_win, "cr_losses": cr_loss, "cr_p": binom_two_sided(min(cr_win, cr_loss), cr_win + cr_loss)}


def main(mode: str = "keyword_only") -> None:
    results = json.loads((HERE / f"results_{mode}.json").read_text(encoding="utf-8"))
    rows = [json.loads(l) for l in (HERE / f"per_question_{mode}.jsonl").read_text(encoding="utf-8").splitlines() if l.strip()]
    tenants = list(results["tenants"])
    names = list(results["tenants"][tenants[0]]["strategies"])
    out = [f"<!-- generated by build_chunking_tables.py from results_{mode}.json / per_question_{mode}.jsonl; do not edit -->", ""]
    summary = {"mode": mode, "pooled": {}}

    out += ["### Harness check: `structure` through this harness against `evaluation.run_retrieval`", "",
            "| Tenant | Split | run_retrieval recall@5 | harness hit@5 | run_retrieval no-answer recall | harness no-answer recall | match |",
            "|---|---|---|---|---|---|---|"]
    for t in tenants:
        for split in ("dev", "test"):
            off = results["tenants"][t]["production_check"][split]
            har = results["tenants"][t]["strategies"][BASE][split]
            ok = abs(off["recall_at_k"] - har["hit_at_5"]) < 1e-9 and abs(off["no_answer_recall"] - har["no_answer_recall"]) < 1e-9 \
                and off["per_style"] == har["per_style"]
            out.append(f"| {t} | {split} | {pct(off['recall_at_k'])} | {pct(har['hit_at_5'])} | {pct(off['no_answer_recall'])} | "
                       f"{pct(har['no_answer_recall'])} | {'yes' if ok else 'NO'} |")
    out.append("")

    out += ["### Chunk statistics (current documents)", "",
            "| Strategy | " + " | ".join(f"{t} chunks / median chars" for t in tenants) + " | chunk+BM25 build ms (sum) |",
            "|---|" + "---|" * (len(tenants) + 1)]
    for n in names:
        cells, ms = [], 0.0
        for t in tenants:
            ix = results["tenants"][t]["strategies"][n]["index"]
            cells.append(f"{ix['chunks']} / {ix['chars_median']:.0f}")
            ms += ix["chunk_ms"] + ix["bm25_ms"]
        out.append(f"| {n} | " + " | ".join(cells) + f" | {ms:.1f} |")
    out.append("")
    out.append("Corpus size (current documents, characters): " +
               ", ".join(f"{t} {results['tenants'][t]['corpus_chars']}" for t in tenants) + ".")
    out.append("")

    for key, label in SETTINGS:
        sel = defaultdict(list)
        for r in rows:
            if r["split"] == "test" and r["thresholds"] == key:
                sel[r["strategy"]].append(r)
        summary["pooled"][key] = {}
        out += [f"### Pooled test split, {label} ({sel[BASE] and sum(r['answerable'] for r in sel[BASE])} answerable, "
                f"{sum(not r['answerable'] for r in sel[BASE])} unanswerable questions)", "",
                "| Strategy | Hit@5 % | Context precision | Context recall | Char precision | No-answer recall % | No-answer precision % | "
                "Avg returned chars | Hit@5 vs structure (won/lost, p) | Context recall vs structure (won/lost, p) |",
                "|---|---|---|---|---|---|---|---|---|---|"]
        for n in names:
            p = pooled(sel[n])
            summary["pooled"][key][n] = p
            if n == BASE:
                cmp_hit = cmp_cr = "baseline"
            else:
                d = paired(sel[n], sel[BASE])
                summary["pooled"][key][n]["paired"] = d
                cmp_hit = f"{d['hit_wins']}/{d['hit_losses']}, p={d['hit_p']:.3f}"
                cmp_cr = f"{d['cr_wins']}/{d['cr_losses']}, p={d['cr_p']:.3f}"
            out.append(f"| {n} | {pct(p['hit_at_5'])} | {p['context_precision']:.3f} | {p['context_recall']:.3f} | "
                       f"{p['char_precision']:.3f} | {pct(p['no_answer_recall'])} | {pct(p['no_answer_precision'])} | "
                       f"{p['avg_returned_chars']:.0f} | {cmp_hit} | {cmp_cr} |")
        out.append("")

    block = {"test": "top 5, shipped thresholds", "test_budget": "1500-character budget, shipped thresholds"}
    for key, label in block.items():
        out += [f"### Per tenant, test split, {label}", "",
                "| Tenant | Strategy | Hit@5 % | Per style | Context precision | Context recall | Char precision | "
                "No-answer recall % | Avg returned chars | Latency p50 / p95 ms |",
                "|---|---|---|---|---|---|---|---|---|---|"]
        for t in tenants:
            for n in names:
                s = results["tenants"][t]["strategies"][n][key]
                styles = ", ".join(f"{k} {v}" for k, v in s["per_style"].items())
                out.append(f"| {t} | {n} | {pct(s['hit_at_5'])} | {styles} | {s['context_precision']:.3f} | {s['context_recall']:.3f} | "
                           f"{s['char_precision']:.3f} | {pct(s['no_answer_recall'])} | {s['avg_returned_chars']:.0f} | "
                           f"{s['latency_ms_p50']:.2f} / {s['latency_ms_p95']:.2f} |")
        out.append("")

    out += ["### Dev-tuned keyword threshold per strategy (test split, top 5)", "",
            "| Strategy | " + " | ".join(f"{t} min_bm25 / hit@5 % / no-answer recall %" for t in tenants) + " |",
            "|---|" + "---|" * len(tenants)]
    for n in names:
        cells = []
        for t in tenants:
            s = results["tenants"][t]["strategies"][n]["test_dev_tuned"]
            cells.append(f"{s['min_bm25']} / {pct(s['hit_at_5'])} / {pct(s['no_answer_recall'])}")
        out.append(f"| {n} | " + " | ".join(cells) + " |")
    out.append("")

    (HERE / f"tables_{mode}.md").write_text("\n".join(out), encoding="utf-8")
    (HERE / f"pooled_{mode}.json").write_text(json.dumps(summary, indent=2), encoding="utf-8")
    print(f"Wrote {HERE / f'tables_{mode}.md'}")


if __name__ == "__main__":
    main(*(sys.argv[1:2] or []))
