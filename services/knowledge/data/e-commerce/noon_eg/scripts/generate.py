def make_tickets(n, decide, start):
    out = []
    first = AS_OF - timedelta(days=365)
    for k in range(n):
        lang = rnd.choices(T.LANGS, (30, 30, 20, 20))[0]
        female = rnd.random() < 0.5
        created = first + timedelta(days=rnd.randint(0, 364))
        if rnd.random() < 0.6:
            section = "minutes" if rnd.random() < 0.18 else "noon"
            keys = MINUTES_KEYS if section == "minutes" else PRODUCT_KEYS
            key = rnd.choices(keys, MINUTES_W if section == "minutes" else PRODUCT_W)[0]
            cat, sub = key
            name = rnd.choice(K.PRODUCTS[key][3])
            cond = rnd.choice(K.conditions_for(cat, sub, section))
            days = rnd.choice([rnd.randint(1, 10), rnd.randint(11, 25)])
            tag = rnd.random() < (0.25 if cat == "grocery" else 0.88)
            warranty = section == "minutes" and cat in {"electronics", "home_kitchen"} and rnd.random() < 0.3
            dec, reason, _ = decide(section, cat, sub, cond, tag, warranty, days, True)
            category = {"OUTSIDE_WINDOW": "return_window", "WARRANTY_SERVICE_CENTER": "warranty"}.get(reason, "return")
            out.append({"ticket_id": f"NT-{start + k}", "tenant_id": TENANT, "category": category,
                        "customer_message": T.return_request(rnd, lang, female, name, days, cond, section),
                        "resolution": T.return_resolution(rnd, reason, section, cat, sub, cond, days),
                        "created_at": iso(created)})
        else:
            kind = rnd.choice(sorted(T.REFUND_RESOLUTION))
            name = rnd.choice(K.PRODUCTS[rnd.choice(PRODUCT_KEYS)][3])
            paid = rnd.randint(30, 300) * 10
            msg = T.refund_message(rnd, lang, female, kind, item=name, n=rnd.randint(3, 20),
                                   provider=rnd.choice(["Tabby", "Tamara"]), paid=paid + 20, refund=paid)
            out.append({"ticket_id": f"NT-{start + k}", "tenant_id": TENANT,
                        "category": T.REFUND_TICKET_CATEGORY[kind], "customer_message": msg,
                        "resolution": T.REFUND_RESOLUTION[kind], "created_at": iso(created)})
    out.sort(key=lambda t: (t["created_at"], t["ticket_id"]))
    return out


# ------------------------------------------------------------------ main

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seed", type=Path, default=TENANT_DIR / "seed", help="hand-built originals")
    ap.add_argument("--out", type=Path, default=TENANT_DIR,
                    help="writes <out>/mock/noon_*.json and <out>/tickets.jsonl")
    ap.add_argument("--customers", type=int, default=5000)
    ap.add_argument("--create-return", type=int, default=600)
    ap.add_argument("--refund-status", type=int, default=240)
    ap.add_argument("--cancel", type=int, default=60)
    ap.add_argument("--tickets", type=int, default=1500)
    args = ap.parse_args()

    orig, ref = load_originals(args.seed)
    decide = ref["decide_return"]
    customers, extra = make_customers(args.customers, {c["email"] for c in orig["customers"]})
    orders = make_orders(customers, extra)
    returns = make_returns(orders, decide)
    settle_wallets(customers, returns)
    cust = {c["customer_id"]: c for c in customers}
    scen = make_create_return(orders, cust, extra, decide, args.create_return, 1)
    scen += make_refund_status(orders, returns, cust, extra, args.refund_status, len(scen) + 1)
    scen += make_cancel(orders, cust, extra, args.cancel, len(scen) + 1)
    tickets = make_tickets(args.tickets, decide, 3001)
    for o in orders:
        o.pop("_return", None)
        o.pop("_scenario", None)
    for r in returns:  # same optional-key style as the originals: absent rather than null
        for key in [k for k, v in r.items() if v is None and k != "refund_destination"]:
            del r[key]

    meta = dict(orig["meta"])
    meta["note"] = (orig["meta"]["note"] + " Bulk extension (Ticket-Easy/Data/ecommerce, seed "
                    f"{SEED}): records after the hand-built ones are generated; shipping fees (30 EGP noon under "
                    "350, 15 EGP Minutes under 150) and all prices are invented.")
    mock = args.out / "mock"
    mock.mkdir(parents=True, exist_ok=True)
    for key, rows in (("customers", orig["customers"] + customers), ("orders", orig["orders"] + orders),
                      ("returns", orig["returns"] + returns), ("scenarios", orig["scenarios"] + scen)):
        (mock / f"noon_{key}.json").write_text(
            json.dumps({"_meta": meta, key: rows}, ensure_ascii=False, indent=2) + "\n", encoding="utf-8", newline="\n")
    (args.out / "tickets.jsonl").write_text(
        "".join(json.dumps(t, ensure_ascii=False) + "\n" for t in orig["tickets"] + tickets), encoding="utf-8",
        newline="\n")

    print(f"customers {len(orig['customers'])} + {len(customers)}; orders {len(orig['orders'])} + {len(orders)} "
          f"({sum(len(o['items']) for o in orders)} items); returns {len(orig['returns'])} + {len(returns)}; "
          f"scenarios {len(orig['scenarios'])} + {len(scen)}; tickets {len(orig['tickets'])} + {len(tickets)}")
    print("order status:", dict(Counter(o["status"] for o in orders)))
    print("return status:", dict(Counter(r["status"] for r in returns)))
    print("scenario types:", dict(Counter(s["type"] for s in scen)))
    print("create_return:", dict(Counter(s["expected"]["reason_code"] for s in scen if s["type"] == "create_return")))
    print("languages:", dict(Counter(s["language"] for s in scen)))


if __name__ == "__main__":
    main()
