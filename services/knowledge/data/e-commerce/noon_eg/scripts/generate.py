import random
import runpy
import zlib
from collections import Counter
from datetime import date, timedelta
from pathlib import Path

import catalog as K
import texts as T

SEED = 20261008
AS_OF = date(2026, 10, 8)
TENANT = "noon_eg"
COD_FEE = 20                      # same invented fee as the originals
NOON_FREE_SHIPPING, NOON_SHIPPING = 350, 30       # invented, like the originals' fees
MINUTES_FREE_SHIPPING, MINUTES_SHIPPING = 150, 15
NOON_RETURN_RATE, MINUTES_RETURN_RATE = 0.09, 0.04

rnd = random.Random(SEED)


def iso(d):
    return d.isoformat() if d else None


def add_business_days(d, n):
    """Egypt's weekend is Friday and Saturday."""
    while n > 0:
        d += timedelta(days=1)
        if d.weekday() not in (4, 5):
            n -= 1
    return d


def business_days_between(a, b):
    n, d = 0, a
    while d < b:
        d += timedelta(days=1)
        if d.weekday() not in (4, 5):
            n += 1
    return n


def price(lo, hi):
    p = rnd.uniform(lo, hi) if hi < 2000 else rnd.triangular(lo, hi, lo + (hi - lo) * 0.3)
    step = 10 if p < 1000 else 50 if p < 10000 else 100
    return int(round(p / step) * step - (1 if rnd.random() < 0.5 else 0))


